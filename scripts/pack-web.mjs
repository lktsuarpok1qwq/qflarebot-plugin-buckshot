import { WEB_TIMING } from '../src/web/timing.ts';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const folder = new URL('../src/web/client/', import.meta.url), files = {};
const css = ['tokens', 'scene', 'base', 'device', 'props', 'cards', 'desktop', 'play'];
const shared = ['sound', 'props', 'effect-layout', 'scene', 'loading', 'presentation'];
const read = name => readFile(new URL(name, folder), 'utf8');

function add(name, body) {
    const filename = name.replace(/(\.[^.]+)$/, '.' + createHash('sha256').update(body).digest('hex').slice(0, 12) + '$1');
    files[filename] = { body, type: name.endsWith('.js') ? 'text/javascript; charset=utf-8' : 'text/css; charset=utf-8' };

    return filename;
}

const style = add('battle.css', (await Promise.all(css.map(name => read(name + '.css')))).join('\n'));
// 保留经典脚本的共享词法作用域和原执行顺序，不引入运行时加载器或第三方依赖。
const scene = add('battle.js', "'use strict';\nconst battleTiming = Object.freeze(" + JSON.stringify(WEB_TIMING) + ');\n' + (await Promise.all(shared.map(name => read(name + '.js')))).join('\n;\n'));
const play = add('play.js', await read('play.js'));
add('replay.js', await read('replay.js'));
const html = (await read('index.html'))
    .replace(/<link rel="stylesheet" href="[^"]+">/g, '')
    .replace('</head>', `<link rel="stylesheet" href="${style}"></head>`)
    .replace(/<script src="[^"]+" defer><\/script>/g, '')
    .replace('</body>', `<script src="${scene}" defer></script><script src="${play}" defer></script></body>`);
files['index.html'] = { body: html, type: 'text/html; charset=utf-8' };
const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 16);
await writeFile(new URL('../src/web/assets.ts', import.meta.url), `// Generated by scripts/pack-web.mjs; edit src/web/client instead.\nimport type { AssetMap } from '@qqbot/sdk';\nexport const assets: AssetMap = ${JSON.stringify({ files, version })};\n`);
